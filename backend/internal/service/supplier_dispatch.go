package service

import (
	"context"
	"errors"
	"time"
)

// These errors are local accounting/authorization failures, never an instruction
// to replay upstream generation. They intentionally contain no credential data.
var (
	ErrSupplierAccountingPending   = errors.New("supplier accounting pending reconciliation")
	ErrSupplierDispatchConflict    = errors.New("supplier dispatch snapshot conflict")
	ErrSupplierDispatchUnavailable = errors.New("supplier durable dispatch unavailable")
)

// SupplierDispatchSnapshot contains only immutable accounting identity and terms.
// It is internal and must not be exposed in supplier or customer HTTP payloads.
type SupplierDispatchSnapshot struct {
	AttemptID            string            `json:"attempt_id"`
	RequestID            string            `json:"request_id"`
	ResourceID           string            `json:"resource_id"`
	SupplierID           int64             `json:"supplier_id"`
	AccountID            int64             `json:"account_id"`
	CredentialVersion    int64             `json:"credential_version"`
	AuthorizationVersion int64             `json:"authorization_version"`
	ConsentVersion       string            `json:"consent_version"`
	UserID               int64             `json:"user_id"`
	APIKeyID             int64             `json:"api_key_id"`
	GroupID              int64             `json:"group_id"`
	Model                string            `json:"model"`
	FeePolicy            SupplierFeePolicy `json:"fee_policy"`
	AcceptedAt           time.Time         `json:"accepted_at"`
	Digest               string            `json:"digest"`
}

// IDs are generated by the server, never from a client-provided request ID.
// Request/account slot acquisition and model capability checks remain owned by
// the existing gateway/scheduler; the repository rechecks durable eligibility.
type SupplierDispatchRequest struct {
	AttemptID  string
	RequestID  string
	ResourceID string
	AccountID  int64
	UserID     int64
	APIKeyID   int64
	GroupID    int64
	Model      string
}

type SupplierAcceptedDispatch struct {
	Snapshot SupplierDispatchSnapshot
	// Resource contains the exact encrypted credential version authorized in the
	// acceptance transaction. Decrypt this value, not a later resource lookup.
	Resource *SupplierResource
}

// SupplierUsageObservation never stores headers, prompts, outputs, or bearer
// values. Missing/ambiguous consumption is represented explicitly, not as zero.
type SupplierUsageObservation struct {
	Usage              OpenAIUsage `json:"usage"`
	UsagePresent       bool        `json:"usage_present"`
	Complete           bool        `json:"complete"`
	Source             string      `json:"source"`
	Terminal           string      `json:"terminal"`
	UpstreamRequestID  string      `json:"upstream_request_id,omitempty"`
	Model              string      `json:"model"`
	ServiceTier        string      `json:"service_tier,omitempty"`
	ReasoningEffort    string      `json:"reasoning_effort,omitempty"`
	ClientDisconnected bool        `json:"client_disconnected"`
	ObservedAt         time.Time   `json:"observed_at"`
}

// SupplierDispatchRepository is implemented alongside UsageBillingRepository so
// accepted intents, staged commands, customer effects and supplier facts share
// PostgreSQL authority and existing customer deduplication. No second ledger.
type SupplierDispatchRepository interface {
	AcceptSupplierDispatch(context.Context, SupplierDispatchRequest) (*SupplierAcceptedDispatch, error)
	MarkSupplierDispatched(context.Context, string, string) error
	ObserveSupplierUsage(context.Context, string, string, SupplierUsageObservation) error
	MarkSupplierReview(context.Context, string, string, string) error
	StageSupplierBilling(context.Context, *UsageBillingCommand) error
	RecoverSupplierBilling(context.Context, int) (SupplierRecoveryResult, error)
}

type SupplierRecoveryResult struct {
	Replayed int
	Pending  int
	Review   int
}
