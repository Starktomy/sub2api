import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount, flushPromises, mount } from '@vue/test-utils'
import Resources from '../Resources.vue'
import { validSessionJSON } from '../resourceTypes'
const mocks = vi.hoisted(() => ({ resources: vi.fn(), importResource: vi.fn(), resourceUsage: vi.fn(), pauseResource: vi.fn(), resumeResourceSync: vi.fn(), disconnectResource: vi.fn() }))
vi.mock('../api', () => ({ isolatedSupplierAPI: mocks, supplierErrorReason: (err: { reason?: string }) => err.reason }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
enableAutoUnmount(afterEach)
afterEach(() => vi.useRealTimers())
const resource = { id: 'resource-test-id', display_name: 'My Codex', status: 'paused', auto_sync_enabled: true, probe_state: 'pending', last_probe_at: null, next_probe_at: null, probe_error_code: null, version: 1, masked_email: 's***@example.test', plan_type: 'plus', usage_state: 'unknown', usage: null, last_usage_at: null, updated_at: '2026-11-03T00:00:00Z', token_expires_at: null }
const session = '{"accessToken":"synthetic-test-only"}'
beforeEach(() => {
  vi.clearAllMocks()
  mocks.resources.mockResolvedValue({ items: [], vault_configured: true })
  mocks.importResource.mockResolvedValue(resource)
  mocks.resourceUsage.mockResolvedValue({ ...resource, version: 2 })
  mocks.disconnectResource.mockResolvedValue({ ...resource, status: 'disconnected', version: 2 })
})
async function importer() {
  const wrapper = mount(Resources)
  await flushPromises()
  await wrapper.get('button').trigger('click')
  await wrapper.get('#resource-name').setValue('My Codex')
  await wrapper.get('#resource-session').setValue(session)
  return wrapper
}
describe('supplier Codex resources', () => {
  it('rejects credential material other than session JSON without echoing it', () => {
    expect(validSessionJSON(session)).toBe(true)
    for (const text of ['[]', 'invalid', '{"password":"test"}', '{"nested":{"cookie":"test"}}', '{"totp_code":"123456"}', '{"session_token":"test"}']) expect(validSessionJSON(text)).toBe(false)
  })
  it('imports minimal fields and clears pasted data after success', async () => {
    const wrapper = await importer()
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(mocks.importResource).toHaveBeenCalledWith('My Codex', session)
    expect(wrapper.find('textarea').exists()).toBe(false)
    await wrapper.get('button').trigger('click')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
    expect(localStorage.getItem('session')).toBeNull()
  })
  it('clears pasted text on cancel and does not submit', async () => {
    const wrapper = await importer()
    await wrapper.get('form button[type="button"]').trigger('click')
    expect(wrapper.find('textarea').exists()).toBe(false)
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('button').trigger('click')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
  })
  it('does not echo server error or retain paste on failed submission', async () => {
    const wrapper = await importer()
    mocks.importResource.mockRejectedValue({ reason: 'SUPPLIER_VAULT_NOT_CONFIGURED', message: session })
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('supplier.importUnconfigured')
    expect(wrapper.html()).not.toContain('synthetic-test-only')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
  })
  it('fails closed when encrypted vault is not configured', async () => {
    mocks.resources.mockResolvedValue({ items: [], vault_configured: false })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.get('button').attributes('disabled')).toBeDefined()
    expect(wrapper.text()).toContain('supplier.importUnconfigured')
  })
  it('renders unknown windows, masked identity and pause state without invented usage', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('s***@example.test')
    expect(wrapper.text()).toContain('supplier.declaredPlan')
    expect(wrapper.text()).toContain('supplier.unknown')
    expect(wrapper.text()).toContain('supplier.notSchedulable')
    expect(wrapper.text()).not.toContain('0%')
  })
  it('renders stale snapshot data without treating it as current capacity', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, usage_state: 'stale', last_usage_at: '2026-11-01T00:00:00Z', usage: { rate_limit: { primary_window: { used_percent: 42, reset_at: 1793721600 }, secondary_window: null } } }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.stale')
    expect(wrapper.text()).toContain('supplier.observedPlan')
    expect(wrapper.text()).toContain('42%')
    expect(wrapper.text()).toContain('supplier.unknown')
    expect(wrapper.text()).toContain('supplier.notSchedulable')
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
  })
  it('shows automatic-sync intent and times without issuing browser probes', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, probe_state: 'retrying', last_probe_at: '2026-11-04T00:00:00Z', next_probe_at: '2026-11-04T00:10:00Z', probe_error_code: 'UNTRUSTED_SECRET_TEXT' }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.syncRequested')
    expect(wrapper.text()).toContain('supplier.syncRetrying')
    expect(wrapper.text()).toContain('supplier.syncWorkerCaveat')
    expect(wrapper.text()).not.toContain('UNTRUSTED_SECRET_TEXT')
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
  })
  it('resumes read-only sync using version, never scheduling', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, auto_sync_enabled: false, probe_state: 'paused' }], vault_configured: true })
    mocks.resumeResourceSync.mockResolvedValue({ ...resource, version: 2 })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.resumeSync')!.trigger('click')
    await flushPromises()
    expect(mocks.resumeResourceSync).toHaveBeenCalledWith(resource.id, 1)
    expect(wrapper.text()).toContain('supplier.notSchedulable')
  })
  it('reconnects only after confirming old credential disconnection', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, auto_sync_enabled: false, probe_state: 'reauthorization_required' }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.reconnect')!.trigger('click')
    expect(wrapper.find('textarea').exists()).toBe(false)
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.confirmDisconnect')!.trigger('click')
    await flushPromises()
    expect(mocks.disconnectResource).toHaveBeenCalledWith(resource.id, 1)
    expect(wrapper.find('textarea').exists()).toBe(true)
    expect(wrapper.text()).toContain('supplier.reconnectReady')
  })
  it('refreshes only the redacted resource list automatically, not provider usage', async () => {
    vi.useFakeTimers()
    const wrapper = mount(Resources)
    await flushPromises()
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.resources).toHaveBeenCalledTimes(2)
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
    wrapper.unmount()
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.resources).toHaveBeenCalledTimes(2)
  })
  it('uses explicit versioned read-only snapshot and disconnect confirmation', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    const buttons = () => wrapper.findAll('li button')
    await buttons()[0].trigger('click')
    await flushPromises()
    expect(mocks.resourceUsage).toHaveBeenCalledWith(resource.id, 1)
    await buttons()[2].trigger('click')
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    await buttons()[3].trigger('click')
    await flushPromises()
    expect(mocks.disconnectResource).toHaveBeenCalledWith(resource.id, 2)
    expect(wrapper.text()).toContain('supplier.disconnected')
  })
})
