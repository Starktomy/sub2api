import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount, flushPromises, mount } from '@vue/test-utils'
import Resources from '../Resources.vue'
import zh from '@/i18n/locales/zh/supplier'
import en from '@/i18n/locales/en/supplier'
import { validSessionJSON, extractSessionJSON } from '../resourceTypes'
const mocks = vi.hoisted(() => ({ resources: vi.fn(), importResource: vi.fn(), resourceUsage: vi.fn(), pauseResource: vi.fn(), startResource: vi.fn(), disconnectResource: vi.fn() }))
vi.mock('../ResourceStats.vue', () => ({ default: { props: ['resourceId'], template: '<section data-testid="resource-stats">{{ resourceId }}</section>' } }))
vi.mock('../api', () => ({ isolatedSupplierAPI: mocks, supplierErrorReason: (err: { reason?: string }) => err.reason }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
enableAutoUnmount(afterEach)
afterEach(() => vi.useRealTimers())
const resource = { id: 'resource-test-id', display_name: 'My Codex', status: 'paused', supply_enabled: false, admin_disabled: false, authorization_version: 1, authorization_expires_at: '2099-01-01T00:00:00Z', auto_sync_enabled: true, probe_state: 'pending', last_probe_at: null, next_probe_at: null, probe_error_code: null, version: 1, masked_email: 's***@example.test', plan_type: 'plus', usage_state: 'unknown', usage: null, last_usage_at: null, updated_at: '2026-11-03T00:00:00Z', token_expires_at: null }
const session = '{"accessToken":"synthetic-test-only"}'
beforeEach(() => {
  vi.clearAllMocks()
  mocks.resources.mockResolvedValue({ items: [], vault_configured: true })
  mocks.importResource.mockResolvedValue(resource)
  mocks.startResource.mockResolvedValue({ ...resource, supply_enabled: true, version: 2 })
  mocks.pauseResource.mockResolvedValue({ ...resource, version: 2 })
  mocks.resourceUsage.mockResolvedValue({ ...resource, version: 2 })
  mocks.disconnectResource.mockResolvedValue({ ...resource, status: 'disconnected', version: 2 })
})
async function importer() {
  const wrapper = mount(Resources)
  await flushPromises()
  await wrapper.get('button').trigger('click')
  await wrapper.get('#resource-name').setValue('My Codex')
  await wrapper.get('#resource-session').setValue(session)
  await wrapper.get('#resource-consent-check').setValue(true)
  return wrapper
}
describe('supplier Codex resources', () => {
  it('rejects contradictory declared emails without interpreting tokens', () => {
    expect(extractSessionJSON(JSON.stringify({ accessToken: 'synthetic', email: 'one@example.invalid', user: { email: 'two@example.invalid' } }))).toBeNull()
    expect(extractSessionJSON(JSON.stringify({ accessToken: 'synthetic', email: ' Same@example.invalid ', user: { email: 'same@EXAMPLE.invalid' } }))).not.toBeNull()
  })
  it.each([
    ['phone_verification_required', 'phoneVerificationRequired'],
    ['identity_email_mismatch', 'identityEmailMismatch'],
    ['identity_unknown', 'identityUnknown']
  ] as const)('translates %s for probe and availability without displaying raw codes', async (code, key) => {
    expect(en[key]).toBeTruthy()
    expect(zh[key]).toBeTruthy()
    for (const field of ['probe_error_code', 'availability_reason']) {
      mocks.resources.mockResolvedValue({ items: [{ ...resource, [field]: code }], vault_configured: true })
      const wrapper = mount(Resources)
      await flushPromises()
      expect(wrapper.text()).toContain(`supplier.${key}`)
      expect(wrapper.text()).not.toContain(code)
      wrapper.unmount()
    }
  })
  it('uses the required Chinese supply labels and discloses continuing consent in both locales', () => {
    expect(zh.authorizeAndStart).toBe('授权全部可用额度并开始供给')
    expect([zh.startSupply, zh.pauseSupply, zh.updateAuthorization, zh.disconnect]).toEqual(['开始供给', '暂停供给', '更新授权', '断开并删除凭据'])
    expect(zh.supplyConsent).toContain('当前及未来重置窗口')
    expect(zh.supplyConsent).toContain('不预留个人额度')
    expect(zh.supplyConsent).toContain('不保证收益')
    expect(zh.supplyConsent).toContain('历史收入保留')
    expect(en.supplyConsent).toContain('current and future reset windows')
    expect(en.supplyConsent).toContain('no personal reserve')
    expect(en.supplyConsent).toContain('earnings are not guaranteed')
    expect(en.supplyConsent).toContain('historical income is retained')
  })
  it('labels the initial import action with the full authorization wording', async () => {
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.get('button').text()).toBe('supplier.authorizeAndStart')
    await wrapper.get('button').trigger('click')
    expect(wrapper.get('button[type="submit"]').text()).toBe('supplier.authorizeAndStart')
  })
  it('extracts a full ChatGPT session without transmitting browser or device data', () => {
    const full = JSON.stringify({ accessToken: 'synthetic', account: { id: 'acct' }, user: { email: 'test@example.test', mfa: true }, sessionToken: 'browser-secret', statsigContext: { ip: 'private-ip' }, marketingEligibility: {} })
    expect(extractSessionJSON(full)).toBe(JSON.stringify({ accessToken: 'synthetic', account_id: 'acct', email: 'test@example.test' }))
    expect(validSessionJSON(full)).toBe(true)
    expect(extractSessionJSON(full)).not.toContain('browser-secret')
  })
  it('rejects credential material other than session JSON without echoing it', () => {
    expect(validSessionJSON(session)).toBe(true)
    for (const text of ['[]', 'invalid', '{"password":"test"}', '{"nested":{"cookie":"test"}}', '{"totp_code":"123456"}', '{"session_token":"test"}']) expect(validSessionJSON(text)).toBe(false)
  })
  it('imports minimal fields and clears pasted data after success', async () => {
    const wrapper = await importer()
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(mocks.importResource).toHaveBeenCalledWith({ display_name: 'My Codex', content: session, consent_version: 'all_available_continuous_v1' })
    expect(wrapper.find('textarea').exists()).toBe(false)
    await wrapper.get('button').trigger('click')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
    expect(localStorage.getItem('session')).toBeNull()
  })
  it('clears pasted text on cancel and does not submit', async () => {
    const wrapper = await importer()
    await wrapper.get('form button[type="button"]').trigger('click')
    expect(wrapper.find('textarea').exists()).toBe(false)
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('button').trigger('click')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
  })
  it('does not echo server error or retain paste on failed submission', async () => {
    const wrapper = await importer()
    mocks.importResource.mockRejectedValue({ reason: 'SUPPLIER_VAULT_NOT_CONFIGURED', message: session })
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toBe('supplier.importUnconfigured')
    expect(wrapper.html()).not.toContain('synthetic-test-only')
    expect((wrapper.get('textarea').element as HTMLTextAreaElement).value).toBe('')
  })
  it('fails closed when encrypted vault is not configured', async () => {
    mocks.resources.mockResolvedValue({ items: [], vault_configured: false })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.get('button').attributes('disabled')).toBeDefined()
    expect(wrapper.text()).toContain('supplier.importUnconfigured')
  })
  it('renders unknown windows, masked identity and pause state without invented usage', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
    expect(wrapper.text()).toContain('s***@example.test')
    expect(wrapper.text()).toContain('supplier.declaredPlan')
    expect(wrapper.text()).toContain('supplier.unknown')
    expect(wrapper.text()).toContain('supplier.notSchedulable')
    expect(wrapper.text()).not.toContain('0%')
  })
  it('renders stale snapshot data without treating it as current capacity', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, usage_state: 'stale', last_usage_at: '2026-11-01T00:00:00Z', usage: { rate_limit: { primary_window: { used_percent: 42, reset_at: 1793721600 }, secondary_window: null } } }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.stale')
    expect(wrapper.text()).toContain('supplier.observedPlan')
    expect(wrapper.text()).toContain('42%')
    expect(wrapper.text()).toContain('supplier.unknown')
    expect(wrapper.text()).toContain('supplier.notSchedulable')
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
  })
  it('uses safe availability messages and handles nullable rollout reasons', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, availability_reason: 'UNTRUSTED_PRIVATE_TEXT' }, { ...resource, id: 'second', availability_reason: null }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.availabilityPending')
    expect(wrapper.text()).not.toContain('UNTRUSTED_PRIVATE_TEXT')
    expect(wrapper.findAll('[data-testid="resource-stats"]')).toHaveLength(2)
  })
  it('shows automatic-sync intent and times without issuing browser probes', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, probe_state: 'retrying', last_probe_at: '2026-11-04T00:00:00Z', next_probe_at: '2026-11-04T00:10:00Z', probe_error_code: 'UNTRUSTED_SECRET_TEXT' }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.syncRequested')
    expect(wrapper.text()).toContain('supplier.syncRetrying')
    expect(wrapper.text()).toContain('supplier.syncWorkerCaveat')
    expect(wrapper.text()).not.toContain('UNTRUSTED_SECRET_TEXT')
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
  })
  it('starts authorized supply with a version, not the read-only sync endpoint', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.startSupply')!.trigger('click')
    await flushPromises()
    expect(mocks.startResource).toHaveBeenCalledWith(resource.id, 1)
    expect(wrapper.text()).toContain('supplier.supplyEnabled')
    expect(wrapper.text()).toContain('supplier.notSchedulable')
  })
  it('pauses supply without disabling read-only quota polling', async () => {
    vi.useFakeTimers()
    mocks.resources.mockResolvedValue({ items: [{ ...resource, supply_enabled: true }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.pauseSupply')!.trigger('click')
    await flushPromises()
    expect(mocks.pauseResource).toHaveBeenCalledWith(resource.id, 1)
    expect(wrapper.text()).toContain('supplier.pausedNotice')
    expect(wrapper.text()).toContain('supplier.syncRequested')
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.resources).toHaveBeenCalledTimes(2)
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
  })
  it('permits pausing pending activation before verification enables supply', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, supply_enabled: false, availability_reason: 'verification_required' }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.verificationPending')
    expect(wrapper.text()).not.toContain('supplier.supplyPaused')
    const pause = wrapper.findAll('li button').find(button => button.text() === 'supplier.pauseSupply')!
    expect(pause.attributes('disabled')).toBeUndefined()
    await pause.trigger('click')
    await flushPromises()
    expect(mocks.pauseResource).toHaveBeenCalledWith(resource.id, 1)
    expect(wrapper.text()).toContain('supplier.pausedNotice')
  })
  it('opens an authorization update without disconnecting and preserves the resource and stats', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, probe_state: 'reauthorization_required' }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.updateAuthorization')!.trigger('click')
    expect(wrapper.find('textarea').exists()).toBe(true)
    expect((wrapper.get('#resource-name').element as HTMLInputElement).value).toBe('My Codex')
    expect((wrapper.get('#resource-consent-check').element as HTMLInputElement).checked).toBe(false)
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('#resource-session').setValue(session)
    await wrapper.get('#resource-consent-check').setValue(true)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(mocks.importResource).toHaveBeenCalledWith({ display_name: 'My Codex', content: session, consent_version: 'all_available_continuous_v1', resource_id: resource.id, resource_version: 1 })
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
  })
  it('updates a disconnected resource in place without starting it before fresh consent', async () => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, status: 'disconnected', version: 7, authorization_expires_at: null }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    expect(wrapper.findAll('li button').some(button => button.text() === 'supplier.startSupply')).toBe(false)
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.updateAuthorization')!.trigger('click')
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
    await wrapper.get('#resource-session').setValue(session)
    await wrapper.get('form').trigger('submit')
    expect(mocks.importResource).not.toHaveBeenCalled()
    expect(mocks.startResource).not.toHaveBeenCalled()
    await wrapper.get('#resource-consent-check').setValue(true)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(mocks.importResource).toHaveBeenCalledWith({ display_name: 'My Codex', content: session, consent_version: 'all_available_continuous_v1', resource_id: resource.id, resource_version: 7 })
    expect(mocks.startResource).not.toHaveBeenCalled()
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
  })
  it('cancels an authorization update without changing the original resource or history', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.updateAuthorization')!.trigger('click')
    await wrapper.get('#resource-session').setValue(session)
    await wrapper.get('form button[type="button"]').trigger('click')
    expect(mocks.importResource).not.toHaveBeenCalled()
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
  })
  it.each([
    { admin_disabled: true },
    { authorization_version: 0 },
    { authorization_expires_at: '2000-01-01T00:00:00Z' },
    { authorization_expires_at: null },
    { authorization_expires_at: 'not-a-timestamp' },
    { admin_disabled: undefined, authorization_version: undefined, authorization_expires_at: undefined },
  ])('blocks starting supply with restricted or missing authorization fields %j', async fields => {
    mocks.resources.mockResolvedValue({ items: [{ ...resource, ...fields }], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    const start = wrapper.findAll('li button').find(button => button.text() === 'supplier.startSupply')!
    expect(start.attributes('disabled')).toBeDefined()
    await start.trigger('click')
    expect(mocks.startResource).not.toHaveBeenCalled()
    if (fields.admin_disabled) expect(wrapper.text()).toContain('supplier.adminDisabledNotice')
  })
  it('requires a fresh explicit checkbox and sends nothing on checkbox changes alone', async () => {
    const wrapper = await importer()
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('#resource-consent-check').setValue(false)
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.get('form').trigger('submit')
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('#resource-consent-check').setValue(true)
    expect(mocks.importResource).not.toHaveBeenCalled()
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(mocks.importResource).toHaveBeenCalledTimes(1)
    await wrapper.get('button').trigger('click')
    expect((wrapper.get('#resource-consent-check').element as HTMLInputElement).checked).toBe(false)
  })
  it('keeps the original update target and history on version conflicts without retrying', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    mocks.importResource.mockRejectedValue({ reason: 'SUPPLIER_RESOURCE_VERSION_CONFLICT' })
    const wrapper = mount(Resources)
    await flushPromises()
    await wrapper.findAll('li button').find(button => button.text() === 'supplier.updateAuthorization')!.trigger('click')
    await wrapper.get('#resource-session').setValue(session)
    await wrapper.get('#resource-consent-check').setValue(true)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(wrapper.text()).toContain('supplier.resourceConflict')
    expect(mocks.importResource).toHaveBeenCalledTimes(1)
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    expect(wrapper.get('[data-testid="resource-stats"]').text()).toBe(resource.id)
    expect((wrapper.get('#resource-consent-check').element as HTMLInputElement).checked).toBe(false)
    expect((wrapper.get('#resource-session').element as HTMLTextAreaElement).value).toBe('')
  })
  it('refreshes only the redacted resource list automatically, not provider usage', async () => {
    vi.useFakeTimers()
    const wrapper = mount(Resources)
    await flushPromises()
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.resources).toHaveBeenCalledTimes(2)
    expect(mocks.resourceUsage).not.toHaveBeenCalled()
    wrapper.unmount()
    await vi.advanceTimersByTimeAsync(30000)
    expect(mocks.resources).toHaveBeenCalledTimes(2)
  })
  it('uses explicit versioned read-only snapshot and disconnect confirmation', async () => {
    mocks.resources.mockResolvedValue({ items: [resource], vault_configured: true })
    const wrapper = mount(Resources)
    await flushPromises()
    const buttons = () => wrapper.findAll('li button')
    await buttons()[0].trigger('click')
    await flushPromises()
    expect(mocks.resourceUsage).toHaveBeenCalledWith(resource.id, 1)
    await buttons().find(button => button.text() === 'supplier.disconnect')!.trigger('click')
    expect(mocks.disconnectResource).not.toHaveBeenCalled()
    await buttons().find(button => button.text() === 'supplier.confirmDisconnect')!.trigger('click')
    await flushPromises()
    expect(mocks.disconnectResource).toHaveBeenCalledWith(resource.id, 2)
    expect(wrapper.text()).toContain('supplier.disconnected')
  })
})
